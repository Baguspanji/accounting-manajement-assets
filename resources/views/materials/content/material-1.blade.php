            Secara umum, sistem konvensional menggunakan mekanisme bunga (riba) sebagai imbalan, sedangkan sistem syariah
            menghindari bunga dan menggantinya dengan konsep bagi hasil (profit-sharing), margin, atau imbalan (hibah)

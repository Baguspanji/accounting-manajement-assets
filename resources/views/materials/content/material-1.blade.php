                    <li>Pinjaman dengan suku bunga tetap atau mengambang</li>
                    <li>Denda keterlambatan berbunga</li>
                    <li>Diakui sebagai piutang biasa dengan bunga sebagai pendapatan</li>
                </ul>
            </div>
            <div>
                <h3 class="font-semibold text-slate-800 mb-3">Syariah</h3>
                <ul class="list-disc list-inside text-slate-600 space-y-2">
                    <li><strong>Qardh Hasan:</strong> Pinjaman sosial tanpa keuntungan</li>
                    <li><strong>Murabahah:</strong> Jual beli dengan margin yang dijelaskan di awal</li>
                    <li><strong>Musyarakah:</strong> Modal bersama dengan bagi hasil</li>
                    <li><strong>Ijarah:</strong> Sewa guna aset</li>
                    <li>Tidak mengenakan bunga; denda keterlambatan untuk dana sosial</li>
                </ul>
            </div>
        </div>

                    <li>Tidak ada bunga resmi atas simpanan</li>
                    <li>Penarikan sesuai kebijakan koperasi</li>
                </ul>
            </div>
            <div>
                <h3 class="font-semibold text-slate-800 mb-3">Syariah</h3>
                <ul class="list-disc list-inside text-slate-600 space-y-2">
                    <li><strong>Wadiah:</strong> Titipan amanah tanpa imbal hasil pasti</li>
                    <li><strong>Mudharabah:</strong> Bagi hasil antara pemilik dana dan pengelola</li>
                    <li>Imbalan atau bagi hasil maksimal 9% per tahun</li>
                </ul>
            </div>
        </div>

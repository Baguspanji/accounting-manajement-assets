<h2 class="text-xl font-bold text-slate-800 mb-4">4. Siklus Hidup Aset</h2>
<p class="text-slate-600 leading-relaxed mb-4">
    Manajemen aset mencakup seluruh siklus hidup aset, dari perolehan hingga pelepasan:
</p>
<ol class="list-decimal list-inside space-y-2 text-slate-600">
    <li><strong>Perolehan</strong> — pencatatan aset sebesar harga perolehan (biaya yang dikapitalisasi).</li>
    <li><strong>Penyusutan</strong> — alokasi biaya secara sistematis selama umur manfaat.</li>
    <li><strong>Pelepasan/Penghapusan</strong> — pengeluaran aset dari pembukuan saat dijual atau tidak berguna lagi.</li>
    <li><strong>Pelaporan</strong> — penyajian nilai buku aset dalam neraca.</li>
</ol>
        <h2 class="text-xl font-bold text-slate-800 mb-4">1. Definisi dan Prinsip Dasar</h2>
        <div class="space-y-4">
            <div>
                <h3 class="font-semibold text-slate-800 mb-2">Konvensional</h3>
                <p class="text-slate-600 leading-relaxed">
                    Koperasi Simpan Pinjam (KSP) adalah lembaga koperasi yang kegiatannya hanya usaha simpan pinjam.
                    Dalam praktik konvensional, simpan pinjam dioperasikan dengan menerapkan suku bunga tetap atau
                    mengambang pada pinjaman. Sistem ini tidak mensyaratkan prinsip syariah.
                </p>
            </div>
            <div>
                <h3 class="font-semibold text-slate-800 mb-2">Syariah</h3>
                <p class="text-slate-600 leading-relaxed">
                    KSP/S adalah Koperasi Simpan Pinjam dan Pembiayaan Syariah yang hanya melaksanakan usaha simpan,
                    pinjam, dan pembiayaan sesuai prinsip Islam, termasuk mengelola dana zakat, infak, dan sedekah.
                    Prinsip dasar meliputi keharaman riba (bunga), larangan maisir (spekulasi) dan gharar
                    (ketidakjelasan), serta keadilan dan kemitraan.
                </p>
            </div>
        </div>
    </div>


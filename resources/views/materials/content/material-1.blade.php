<h1 class="text-2xl font-bold text-slate-800 mb-4">Pengertian & Karakteristik Aset Tetap</h1>
<p class="text-slate-600 leading-relaxed mb-4">
    Menurut PSAK 216 (penomoran terbaru dari PSAK 16, selaras dengan IAS 16), aset tetap adalah aset berwujud yang
    dimiliki untuk digunakan dalam produksi atau penyediaan barang/jasa, untuk direntalkan kepada pihak lain, atau untuk
    tujuan administratif, dan diperkirakan digunakan lebih dari satu periode akuntansi.
</p>

<h2 class="text-xl font-bold text-slate-800 mb-4">1. Karakteristik Aset Tetap</h2>
<div class="grid grid-cols-1 md:grid-cols-2 gap-4 mb-6">
    <div class="bg-slate-50 rounded-xl p-5 border border-slate-100">
        <h3 class="font-semibold text-slate-800 mb-2">Berwujud (Tangible)</h3>
        <p class="text-sm text-slate-600 leading-relaxed">
            Memiliki bentuk fisik nyata: tanah, bangunan, mesin, kendaraan, peralatan, dan komputer/elektronik.
        </p>
    </div>
    <div class="bg-slate-50 rounded-xl p-5 border border-slate-100">
        <h3 class="font-semibold text-slate-800 mb-2">Bukan untuk Dijual Kembali</h3>
        <p class="text-sm text-slate-600 leading-relaxed">
            Digunakan dalam kegiatan operasional perusahaan, bukan diperjualbelikan sebagai barang dagangan.
        </p>
    </div>
    <div class="bg-slate-50 rounded-xl p-5 border border-slate-100">
        <h3 class="font-semibold text-slate-800 mb-2">Masa Manfaat Lebih dari Satu Periode</h3>
        <p class="text-sm text-slate-600 leading-relaxed">
            Umur manfaat lebih dari 12 bulan dan tidak habis dalam satu siklus operasi normal.
        </p>
    </div>
    <div class="bg-slate-50 rounded-xl p-5 border border-slate-100">
        <h3 class="font-semibold text-slate-800 mb-2">Nilai Material</h3>
        <p class="text-sm text-slate-600 leading-relaxed">
            Nilai perolehannya cukup signifikan sehingga melewati batas kapitalisasi organisasi.
        </p>
    </div>
</div>

<h2 class="text-xl font-bold text-slate-800 mb-4">2. Kriteria Pengakuan</h2>
<p class="text-slate-600 leading-relaxed mb-4">
    Suatu aset diakui sebagai aset tetap jika memenuhi <strong>kedua</strong> kriteria berikut secara bersamaan:
</p>
<ol class="list-decimal list-inside space-y-2 text-slate-600 mb-6">
    <li><strong>Manfaat ekonomi masa depan</strong> kemungkinan besar akan diperoleh entitas dari aset tersebut.</li>
    <li><strong>Biaya perolehan</strong> dapat diukur dengan andal berdasarkan bukti objektif.</li>
</ol>

